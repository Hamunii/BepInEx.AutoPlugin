using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace BepInEx.AutoPlugin;

[Generator]
public sealed class AutoPluginGenerator : IIncrementalGenerator
{
    public const string BepInAutoPluginAttribute = "BepInEx.BepInAutoPluginAttribute";
    public const string PatcherAutoPluginAttribute =
        "BepInEx.Preloader.Core.Patching.PatcherAutoPluginAttribute";
    const string BepInPluginAttribute = "BepInEx.BepInPlugin";
    const string PatcherPluginInfoAttribute = "BepInEx.Preloader.Core.Patching.PatcherPluginInfo";
    const string AttributeCode = """
        // <auto-generated />
        #nullable enable
        namespace BepInEx
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
            [global::System.Diagnostics.Conditional("CodeGeneration")]
            internal sealed class BepInAutoPluginAttribute : global::System.Attribute
            {
                public BepInAutoPluginAttribute(string? id = null, string? name = null, string? version = null) {}
            }
        }

        namespace BepInEx.Preloader.Core.Patching
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
            [global::System.Diagnostics.Conditional("CodeGeneration")]
            internal sealed class PatcherAutoPluginAttribute : global::System.Attribute
            {
                public PatcherAutoPluginAttribute(string? id = null, string? name = null, string? version = null) {}
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddSource("BepInAutoPluginAttribute.g.cs", AttributeCode);
        });

        var references = context.CompilationProvider.Select(
            (compilation, _) => compilation.ReferencedAssemblyNames
        );

        IncrementalValueProvider<bool> isBepInEx5 = references.Select(
            (refs, _) =>
            {
                var bepInEx = refs.FirstOrDefault(r => r.Name.Equals("BepInEx"));

                // BepInEx 5 doesn't support plugins having version pre-release or build metadata
                // such as 1.0.0-beta or 1.0.0+97ec53d20958b88581680d4d3c15ba59a8900ed5
                bool isBepInEx5 = bepInEx is not null && bepInEx.Version.Major == 5;

                return isBepInEx5;
            }
        );

        IncrementalValueProvider<PluginProps> pluginProps = context
            .AnalyzerConfigOptionsProvider.Combine(isBepInEx5)
            .Select(
                static (info, _) =>
                {
                    var (options, isBepInEx5) = info;
                    options.GlobalOptions.TryGetValue(
                        "build_property.AssemblyName",
                        out var assemblyName
                    );
                    options.GlobalOptions.TryGetValue(
                        "build_property.Product",
                        out var productName
                    );
                    options.GlobalOptions.TryGetValue("build_property.Version", out var version);
                    options.GlobalOptions.TryGetValue(
                        "build_property.BepInAutoPluginStripBuildMetadata",
                        out var stripMetadata
                    );

                    // Afaik these should always be set.
                    assemblyName ??= "unknown";
                    productName ??= "unknown";
                    version ??= "0.0.0.0";

                    bool isStripMetadata =
                        stripMetadata?.Equals("true", StringComparison.InvariantCultureIgnoreCase)
                        ?? false;

                    if (isBepInEx5)
                    {
                        version = version.Split('-', '+')[0];
                    }
                    else if (isStripMetadata)
                    {
                        version = version.Split('+')[0];
                    }

                    return new PluginProps(assemblyName, productName, version);
                }
            );

        IncrementalValuesProvider<PluginClass> classesWithBepInAutoPlugin = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                BepInAutoPluginAttribute,
                static (s, _) => IsValidPluginClass(s),
                static (ctx, _) => ToPluginClass(ctx)
            )
            .Where(x => x != default);

        context.RegisterSourceOutput(
            classesWithBepInAutoPlugin.Combine(pluginProps),
            static (context, source) => WriteClass(context, source, BepInPluginAttribute)
        );

        IncrementalValuesProvider<PluginClass> classesWithPatcherAutoPlugin = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                PatcherAutoPluginAttribute,
                static (s, _) => IsValidPluginClass(s),
                static (ctx, _) => ToPluginClass(ctx)
            )
            .Where(x => x != default);

        context.RegisterSourceOutput(
            classesWithPatcherAutoPlugin.Combine(pluginProps),
            static (context, source) => WriteClass(context, source, PatcherPluginInfoAttribute)
        );
    }

    static bool IsValidPluginClass(SyntaxNode node)
    {
        if (node is not ClassDeclarationSyntax { Parent: not TypeDeclarationSyntax } classSyntax)
        {
            return false;
        }

        if (!classSyntax.Modifiers.Any(SyntaxKind.PartialKeyword))
            return false;

        return true;
    }

    static PluginClass ToPluginClass(GeneratorAttributeSyntaxContext ctx)
    {
        var target = (ClassDeclarationSyntax)ctx.TargetNode;
        if (ctx.SemanticModel.GetDeclaredSymbol(target) is not INamedTypeSymbol typeSymbol)
        {
            return default;
        }

        var autoAttribute = ctx.Attributes.First();

        if (autoAttribute is null || autoAttribute.ConstructorArguments.Length != 3)
            return default;

        string? id = autoAttribute.ConstructorArguments[0].Value as string;
        string? name = autoAttribute.ConstructorArguments[1].Value as string;
        string? version = autoAttribute.ConstructorArguments[2].Value as string;

        var ns = typeSymbol.ContainingNamespace;
        var containingNamespace = ns.IsGlobalNamespace ? null : ns.ToDisplayString();

        return new PluginClass(
            containingNamespace,
            typeSymbol.Name,
            new PropOverrides(id, name, version)
        );
    }

    static void WriteClass(
        SourceProductionContext context,
        (PluginClass plugin, PluginProps pluginProps) source,
        string attribute
    )
    {
        try
        {
            var (plugin, props) = source;

            StringBuilder sb = new();

            sb.AppendLine("// <auto-generated />");

            PropOverrides overrides = plugin.Overrides;
            string id = SymbolDisplay.FormatLiteral(overrides.Id ?? props.Id, true);
            string name = SymbolDisplay.FormatLiteral(overrides.Name ?? props.Name, true);
            string version = SymbolDisplay.FormatLiteral(overrides.Version ?? props.Version, true);
            string pluginClass = plugin.ClassName;

            if (plugin.Namespace is not null)
            {
                sb.Append("namespace ").AppendLine(plugin.Namespace).AppendLine("{");
            }

            var classStr = $$"""
                    [global::{{attribute}}({{pluginClass}}.Id, {{name}}, {{version}})]
                    partial class {{pluginClass}}
                    {
                        /// <summary>
                        /// The Id of <see cref="{{pluginClass}}"/>.
                        /// </summary>
                        public const string Id = {{id}};

                        /// <summary>
                        /// Gets the name of <see cref="{{pluginClass}}"/>.
                        /// </summary>
                        public static string Name => {{name}};

                        /// <summary>
                        /// Gets the version of <see cref="{{pluginClass}}"/>.
                        /// </summary>
                        public static string Version => {{version}};
                    }
                """;

            sb.AppendLine(classStr);

            if (plugin.Namespace is not null)
            {
                sb.AppendLine("}");
            }

            var fileName = $"{plugin.Namespace}.{plugin.ClassName}.AutoPlugin.g.cs";
            context.AddSource(fileName, sb.ToString());
        }
        catch (Exception ex)
        {
            throw new Exception(ex.ToString().Replace('\n', ','));
        }
    }

    public readonly record struct PluginClass(
        string? Namespace,
        string ClassName,
        PropOverrides Overrides
    );

    public readonly record struct PropOverrides(string? Id, string? Name, string? Version);

    public readonly record struct PluginProps(string Id, string Name, string Version);
}
